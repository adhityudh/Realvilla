async function translateText(text) {
  if (!text || text.trim() === '') return text;
  try {
    const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=es&dt=t&q=${encodeURIComponent(text)}`;
    const res = await fetch(url);
    const data = await res.json();
    return data[0].map(item => item[0]).join('');
  } catch (error) {
    console.error(`Failed to translate: "${text.substring(0, 40)}..."`, error.message);
    return text;
  }
}

async function sleep(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

async function translateBlocks(blocks) {
  const translated = JSON.parse(JSON.stringify(blocks));
  for (const blk of translated) {
    if (blk.children && blk.children[0]) {
      blk.children[0].text = await translateText(blk.children[0].text);
      await sleep(150);
    }
  }
  return translated;
}

function makeHeroSection(title) {
  return {
    _key: rk(), _type: 'generalHeroSection',
    id: 'general-hero', title,
    desktopLayout: 'vertical',
    disableEntranceAnimation: false,
    disableHeaderEntranceAnimation: false,
    backgroundImage: { _type: 'image', asset: { _type: 'reference', _ref: HERO_BG_DESKTOP } },
    backgroundImageMobile: { _type: 'image', asset: { _type: 'reference', _ref: HERO_BG_MOBILE } },
    primaryButton: { linkType: 'external', openInNewWindow: false },
    secondaryButton: { linkType: 'external', openInNewWindow: false },
  };
}

function makeDocSection(body, tocLabel) {
  return {
    _key: rk(), _type: 'generalDocumentSection',
    anchor: 'legal-notice', tocLabel, body,
  };
}

